#!/usr/bin/env python3
"""Generate markdown comparison report from F-experiment CSV.

Reads ``.pytest_cache/auto_beq_f_experiments.csv`` (produced by
``test_f_experiment_comparison``) and outputs a markdown report
comparing all experiment variants against the baseline.

Usage::

    bin/beq-designer f-experiment-report
    bin/beq-designer f-experiment-report -o docs/f_experiments.md
"""
from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

from cli.report_base import create_report_argparser, run_report


def _load_csv(path: Path) -> list[dict]:
    with path.open() as f:
        return list(csv.DictReader(f))


def generate_report(csv_path: Path, output=None) -> None:
    pr = lambda s="": print(s, file=output or sys.stdout)

    rows = _load_csv(csv_path)
    if not rows:
        pr("No data in CSV.")
        return

    # Group by experiment.
    by_exp: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_exp[r["experiment"]].append(r)

    # --- Summary table ---
    pr("# F-Experiment Comparison Report")
    pr()
    pr(f"**Source**: `{csv_path}`")
    pr()

    # Baseline stats for delta computation.
    baseline_by_title: dict[str, float] = {}
    if "Baseline" in by_exp:
        for r in by_exp["Baseline"]:
            baseline_by_title[r["title"]] = float(r["loss_db"])
    baseline_mean = (
        sum(baseline_by_title.values()) / len(baseline_by_title)
        if baseline_by_title else 0
    )

    pr("## Summary")
    pr()
    pr("| Experiment | Titles | Mean dB | P | M | F | Delta vs Baseline | Improved | Degraded |")
    pr("|---|---|---|---|---|---|---|---|---|")

    for exp_name, exp_rows in by_exp.items():
        losses = [float(r["loss_db"]) for r in exp_rows]
        mean = sum(losses) / len(losses) if losses else 0
        n_p = sum(1 for r in exp_rows if r["verdict"] == "PASS")
        n_m = sum(1 for r in exp_rows if r["verdict"] == "MARGINAL")
        n_f = sum(1 for r in exp_rows if r["verdict"] == "FAIL")
        delta = mean - baseline_mean if baseline_by_title else 0

        # Grade changes vs baseline.
        grade_rank = {"PASS": 0, "MARGINAL": 1, "FAIL": 2}
        improved = degraded = 0
        if exp_name != "Baseline" and baseline_by_title:
            baseline_verdicts = {r["title"]: r["verdict"] for r in by_exp.get("Baseline", [])}
            for r in exp_rows:
                bv = baseline_verdicts.get(r["title"])
                if bv:
                    if grade_rank.get(r["verdict"], 2) < grade_rank.get(bv, 2):
                        improved += 1
                    elif grade_rank.get(r["verdict"], 2) > grade_rank.get(bv, 2):
                        degraded += 1

        delta_str = f"{delta:+.2f}" if exp_name != "Baseline" else "—"
        pr(
            f"| {exp_name} | {len(exp_rows)} | {mean:.2f} | "
            f"{n_p} | {n_m} | {n_f} | {delta_str} | {improved} | {degraded} |"
        )

    # --- Per-author breakdown for best experiment ---
    best_exp = min(by_exp.items(), key=lambda kv: sum(float(r["loss_db"]) for r in kv[1]) / len(kv[1]))
    best_name, best_rows = best_exp
    pr()
    pr(f"## Best experiment: **{best_name}**")
    pr()

    by_author: dict[str, list[float]] = defaultdict(list)
    for r in best_rows:
        by_author[r["author"]].append(float(r["loss_db"]))

    pr("| Author | Titles | Mean dB | < 2 dB | > 5 dB |")
    pr("|---|---|---|---|---|")
    for author, losses in sorted(by_author.items(), key=lambda kv: -len(kv[1])):
        mean_a = sum(losses) / len(losses)
        under2 = sum(1 for l in losses if l < 2)
        over5 = sum(1 for l in losses if l > 5)
        pr(f"| {author} | {len(losses)} | {mean_a:.2f} | {under2} | {over5} |")

    # --- Top improvements vs baseline ---
    if baseline_by_title and best_name != "Baseline":
        pr()
        pr("## Biggest improvements vs baseline")
        pr()
        deltas = []
        for r in best_rows:
            bl = baseline_by_title.get(r["title"])
            if bl is not None:
                deltas.append((r["title"], float(r["loss_db"]) - bl, float(r["loss_db"]), bl))
        deltas.sort(key=lambda x: x[1])

        pr("| Title | Baseline | Best | Delta |")
        pr("|---|---|---|---|")
        for title, d, best_loss, bl_loss in deltas[:15]:
            pr(f"| {title[:40]} | {bl_loss:.2f} | {best_loss:.2f} | {d:+.2f} |")

    pr()
    pr("---")
    pr("Generated by `bin/beq-designer f-experiment-report`")


def main(argv: list[str] | None = None):
    parser = create_report_argparser(
        "F-experiment comparison report",
        extra_args=[
            (("--csv",), {
                "type": Path,
                "default": Path(".pytest_cache/auto_beq_f_experiments.csv"),
                "help": "Path to CSV from test_f_experiment_comparison",
            }),
        ],
    )
    args = parser.parse_args(argv)

    if not args.csv.exists():
        print(f"CSV not found: {args.csv}")
        print("Run test_f_experiment_comparison first.")
        sys.exit(1)

    run_report(generate_report, args, extra_kwargs={"csv_path": args.csv})


if __name__ == "__main__":
    main()
